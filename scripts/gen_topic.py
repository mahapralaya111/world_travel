# -*- coding: utf-8 -*-
from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn

doc = Document()

style = doc.styles['Normal']
style.font.name = '宋体'
style.font.size = Pt(12)
style.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
style.paragraph_format.line_spacing = 1.5
style.paragraph_format.first_line_indent = Cm(0.74)

def h1(text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = '黑体'
    run.font.size = Pt(16)
    run.bold = True
    run.element.rPr.rFonts.set(qn('w:eastAsia'), '黑体')

def body(text, bold=False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = '宋体'
    run.font.size = Pt(12)
    run.bold = bold
    run.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')

def sub(text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = '宋体'
    run.font.size = Pt(12)
    run.bold = True
    run.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')

# ===== 标题 =====
title = doc.add_paragraph()
title.alignment = WD_ALIGN_PARAGRAPH.CENTER
run = title.add_run('基于交互式世界地图的国际旅游规划助手')
run.font.name = '黑体'
run.font.size = Pt(22)
run.bold = True
run.element.rPr.rFonts.set(qn('w:eastAsia'), '黑体')

doc.add_paragraph()

# ===== 一、题目的意义 =====
h1('一、题目的意义')

body('近年来，随着出境游越来越普及，越来越多的人需要规划自己的国际旅行。然而在实际规划过程中，用户面临着几个普遍的痛点：')
body('第一，信息分散。景点介绍、交通攻略、住宿评价散落在携程、马蜂窝、穷游等数十个网站和论坛之间，用户需要反复切换、复制粘贴才能拼凑出一份完整的行程，效率很低。')
body('第二，缺乏空间视角。大多数行程规划工具以时间轴为核心（Day 1 去哪儿、Day 2 去哪儿），但用户很难直观地看到各景点之间的地理关系——两个景点是在同一个城区还是相距 50 公里？路线怎么走最顺？这些问题靠纯文字列表回答不了。')
body('第三，预算估算不合理。用户输入一个总预算后，传统工具往往简单地"平均分摊"到每一天，给出的餐饮、住宿价格脱离当地实际（比如日本一顿拉面 30 元人民币，有的工具却只给 3 毛钱），导致预算参考价值很低。')
body('第四，AI 规划"凑数"。市面上一些 AI 行程规划功能倾向于让同一个景点重复出现（第一天去东京晴空塔，第三天又去东京晴空塔），或者让一个城市承担过多天数导致景点枯竭后被迫重复。')
doc.add_paragraph()
body('本项目要解决的核心问题是：把旅游规划"搬到一张地图上"。让用户能够在交互式世界地图上直接点击国家、批注景点、绘制路线，借助地图的空间可视化能力直观地理解各目的地之间的关系，同时结合大语言模型生成真实、合理的 AI 行程建议。这一课题的意义体现在：')
body('（1）实践意义：为出境旅行者提供一个直观、高效的可视化规划工具，让规划过程从"信息搬运"变成"地图上的创作"，降低国际旅行的规划门槛。', bold=False)
body('（2）技术意义：验证"轻量级前端地图框架（Leaflet）+ Python 后端（Flask）+ SQLite 数据库"这一技术栈在中小型 Web 应用中的可行性，探索大语言模型在垂直领域（旅游规划）的 Prompt 工程与后处理安全网设计。')
body('（3）用户价值：地图交互的方式天然符合人的空间认知习惯——你在纸上画一条路线，比在表格里填 20 行数据更直观、更高效。')

doc.add_paragraph()

# ===== 二、面对的用户 =====
h1('二、面对的用户')

body('本项目面向的是所有有出境旅游需求的个人旅行者，具体来说有以下几类典型用户：')

sub('1. 大学生青年群体')
body('他们预算有限但时间充裕，喜欢自由行，追求个性化路线，对新事物接受度高。他们往往会提前 1-2 个月规划一次毕业旅行或寒暑假出游，希望找到别人没走过的小众路线，同时希望能把自己的规划过程整理成游记分享给同学。')

sub('2. 职场白领')
body('他们每年有 1-2 次出境假期（如年假 + 周末拼接），预算相对充足，但时间紧张，希望高效规划。他们不关心太多细节，需要 AI 快速给出一份合理的方案，调整两三天就能用。')

sub('3. 家庭出游群体')
body('他们以家庭为单位出行，需要考虑老人和孩子的身体状况，行程节奏不宜过紧。他们希望在地图上清楚看到每天住哪里、景点之间距离多远，避免安排不合理的长途奔波。')

sub('4. 旅行爱好者')
body('他们有多次出境经验，追求深度游和小众目的地，愿意花时间精细规划每一段路线。他们需要自由绘制路线的能力（比如规划一条沿美国一号公路的自驾路线），也需要在地图上详细标注每个值得停留的地点和原因。')

doc.add_paragraph()
body('以上用户群体的共同特点是：他们需要在"多个国家/城市 × 多天行程 × 有限预算"的三维约束下做出决策，而地图是帮助他们理解空间关系、平衡各项约束的最直观工具。现有产品要么不支持地图交互（穷游行程助手），要么只支持地图搜索不支持自由绘制（Google Maps），本项目正好填补了这一空白。')

doc.add_paragraph()

# ===== 三、大概的功能 =====
h1('三、大概的功能')

body('系统围绕"交互式世界地图"这一核心，提供以下几类功能：')

sub('1. 地图浏览与国家规划')
body('打开网站首先看到一张中文标注的世界地图（底图使用腾讯/高德中文瓦片源，加载失败自动切换备用源）。点击任意国家，地图会自动放大到该国，进入"该国规划视图"。已经添加过批注或路线的国家会高亮显示，让用户一眼看出自己规划了哪些地方。')

sub('2. 地图批注（打点笔记）')
body('进入国家视图后，点击工具栏的"添加批注"按钮，然后在地图上任意位置点击即可放置一个批注标记，弹出对话框输入标题和详细内容（比如"2026 年 8 月打算去这里吃寿司"）。保存后该位置会出现一个红色圆点标记，鼠标悬停可查看详情。进入删除模式后点击标记可删除。')

sub('3. 路线绘制')
body('点击工具栏的"绘制路线"按钮进入绘制模式，然后在地图上依次点击多个路径点（比如从东京市区到富士山），最后**双击**完成绘制，弹出命名对话框（如"东京→富士山自驾"），还可以选择颜色区分不同路线。保存后地图上会显示一条彩色实线连接所有路径点，起终点有特殊标记。')

sub('4. 多语言城市搜索')
body('在搜索框输入关键词，可以找到全球任意城市。支持中文、英文、拼音、当地文字四种输入方式——输入"beijing"能搜到北京，输入"bj"也能搜到，输入"京"也能匹配。搜索结果按人口、首都标记、是否有景点等权重排序。')

sub('5. AI 智能行程规划')
body('点击"AI 出行规划"按钮，输入出行月份、天数、总预算、出行人数、出发城市和旅行偏好（如自然风光/历史人文/美食购物），AI 会调用大语言模型生成一份完整的出行规划，包括：')
body('（1）目的地推荐：根据天数分配多个城市（13 天日本游不会只堆在东京，而是东京 + 大阪 + 京都 + 奈良多城市组合）；')
body('（2）交通与住宿建议：结合出发城市和出行月份给出合理的交通方式、住宿区域和预算估算；')
body('（3）每日行程：Day 1 上午去哪儿、中午吃什么、下午逛哪里，一天的节奏安排；')
body('（4）预算拆分：交通、住宿、餐饮、门票分别花多少钱，金额符合当地真实物价（日本拉面 30 元、东京晴空塔门票 200 元等）。')
body('AI 规划还有两个后处理安全网：自动去除跨天重复的景点、检查单城市停留天数是否过长。预算明显不足时会在 summary 中提示，而不会编造 3 毛钱一顿饭这种离谱价格。')

sub('6. 用户系统与多行程管理')
body('注册登录后可以创建多个行程（比如"日本毕业旅行""东南亚背包游""欧洲蜜月行"），每个行程的批注和路线独立存储。登录状态下所有数据自动同步到服务器，换一台电脑打开也能继续规划。未登录用户也可以使用全部功能，数据暂存在浏览器里。')

sub('7. 游记分享')
body('完成一次旅行后，可以把自己的行程发布为公开游记，其他用户可以浏览、参考。')

sub('8. 个人数据统计')
body('在统计看板可以看到：你一共规划了多少次出行、在地图上标了多少个批注、画了多少条路线、覆盖了多少个国家——直观展示你的旅行足迹。')

# ===== 保存 =====
import os
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '课题说明.docx')
doc.save(out)
print(f'✅ 已生成: {out}')
